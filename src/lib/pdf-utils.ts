import { spawnSync } from "node:child_process";
import zlib from "node:zlib";

function escapePdfString(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
    .replace(/[^\x20-\x7E]/g, " ");
}

function unescapePdfString(raw: string): string {
  return raw
    .replace(/\\\(/g, "(")
    .replace(/\\\)/g, ")")
    .replace(/\\\\/g, "\\")
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "\r")
    .replace(/\\t/g, "\t");
}

// Deterministic minimal PDF 1.4 generator for fixtures and headless fallback.
export function buildSimplePdfBuffer(lines: string[]): Buffer {
  const sanitized = lines.map((line) => escapePdfString(line));
  const streamLines = [
    "BT",
    "/F1 10 Tf",
    "14 TL",
    "50 750 Td",
    ...sanitized.map((line, idx) =>
      idx === 0 ? `(${line}) Tj` : `T* (${line}) Tj`
    ),
    "ET",
  ];
  const streamContent = streamLines.join("\n");
  const streamByteLength = Buffer.byteLength(streamContent, "utf8");

  const objects: string[] = [
    "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
    "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
    "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n",
    `4 0 obj\n<< /Length ${streamByteLength} >>\nstream\n${streamContent}\nendstream\nendobj\n`,
    "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
  ];

  let body = "%PDF-1.4\n";
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(Buffer.byteLength(body, "utf8"));
    body += obj;
  }

  const xrefOffset = Buffer.byteLength(body, "utf8");
  let xref = `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    xref += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  const trailer = `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(body + xref + trailer, "utf8");
}

function extractTextFromPdfStreams(buffer: Buffer): string {
  const rawLatin1 = buffer.toString("latin1");
  const chunks: string[] = [];

  const streamRegex = /stream\r?\n([\s\S]*?)\r?\nendstream/g;
  let match: RegExpExecArray | null;
  while ((match = streamRegex.exec(rawLatin1)) !== null) {
    const rawStream = Buffer.from(match[1], "latin1");
    let decoded = match[1];
    try {
      decoded = zlib.inflateSync(rawStream).toString("latin1");
    } catch {
      // Not FlateDecoded or already plain text stream
    }

    const tjRegex = /\((?:\\.|[^\\()])*\)\s*Tj/g;
    let tjMatch: RegExpExecArray | null;
    while ((tjMatch = tjRegex.exec(decoded)) !== null) {
      const inner = tjMatch[0].replace(/\)\s*Tj$/, "").slice(1);
      chunks.push(unescapePdfString(inner));
    }

    const tjArrayRegex = /\[((?:\\.|[^\]])*)\]\s*TJ/g;
    let arrMatch: RegExpExecArray | null;
    while ((arrMatch = tjArrayRegex.exec(decoded)) !== null) {
      const groupParts: string[] = [];
      const strRegex = /\((?:\\.|[^\\()])*\)/g;
      let strMatch: RegExpExecArray | null;
      while ((strMatch = strRegex.exec(arrMatch[1])) !== null) {
        groupParts.push(unescapePdfString(strMatch[0].slice(1, -1)));
      }
      if (groupParts.length > 0) {
        chunks.push(groupParts.join(""));
      }
    }
  }

  return chunks.join("\n").trim();
}

export async function extractTextFromPdf(
  pdfBytes: Uint8Array | Buffer
): Promise<string> {
  const buf = Buffer.isBuffer(pdfBytes) ? pdfBytes : Buffer.from(pdfBytes);
  if (buf.byteLength === 0) {
    throw new Error("Empty PDF buffer");
  }

  // 1. Try unpdf if present in node_modules
  try {
    const pkgName = "unpdf";
    const unpdfModule = (await import(pkgName)) as {
      extractText?: (data: Uint8Array) => Promise<{ text: string | string[] }>;
    };
    if (typeof unpdfModule.extractText === "function") {
      const res = await unpdfModule.extractText(new Uint8Array(buf));
      const text = Array.isArray(res.text) ? res.text.join("\n") : res.text;
      if (text && text.trim().length > 0) {
        return text.trim();
      }
    }
  } catch {
    // Fallback to stream + pdftotext extraction
  }

  // 2. Pure-TS PDF content stream extraction
  const streamText = extractTextFromPdfStreams(buf);
  if (streamText.length > 0) {
    return streamText;
  }

  // 3. System pdftotext fallback (for complex font-encoded PDFs generated by Chrome)
  try {
    const proc = spawnSync("/usr/bin/pdftotext", ["-", "-"], {
      input: buf,
      encoding: "utf8",
      timeout: 10_000,
    });
    if (proc.status === 0 && proc.stdout && proc.stdout.trim().length > 0) {
      return proc.stdout.trim();
    }
  } catch {
    // ignore if pdftotext unavailable
  }

  throw new Error("Could not extract readable text from PDF");
}
